"""Writes docs/commands.md from the commands themselves (the same text as `qbd help <command>`), so the reference
cannot drift from the code. A test fails when the file is out of date: run this script and commit the result."""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from qbd_agent_kit.cli import COMMANDS, GROUPS, SETUP, command_help, general_help  # noqa: E402

OUT = ROOT / "docs" / "commands.md"


def render() -> str:
    out = [
        "# Commands",
        "",
        "Generated by `scripts/gen-docs.py` from the commands themselves; `qbd help <command>` prints the same text.",
        "Every command prints one line of JSON (add `--pretty` to indent it, `--out FILE` to write it to a file) and",
        "takes `--demo` to run against the built-in sample company instead of QuickBooks.",
        "",
        "```",
        general_help(),
        "```",
    ]
    for title, tools in GROUPS:
        out += ["", f"## {title}"]
        for cmd, t in COMMANDS.items():
            if t in tools:
                out += ["", f"### qbd {cmd}", "", "```", command_help(cmd), "```"]
    out += ["", "## Setup"]
    for cmd, about in SETUP.items():
        out += ["", f"### qbd {cmd}", "", f"{about}."]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    OUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
